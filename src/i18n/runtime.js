const PERSIAN_DIGITS = "۰۱۲۳۴۵۶۷۸۹";

export function getLanguage() {
  if (typeof window === "undefined") return "fa";
  const storedLanguage = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
  return SUPPORTED_LANGUAGES.has(storedLanguage) ? storedLanguage : "fa";
}

export function getDirection(language = getLanguage()) {
  return language === "en" ? "ltr" : "rtl";
}

export function getLocale(language = getLanguage()) {
  return language === "en" ? "en-US" : "fa-IR";
}

export function getPersianCalendarLocale(language = getLanguage()) {
  return language === "en" ? "en-US-u-ca-persian" : "fa-IR-u-ca-persian";
}

export function initializeLanguageDocument() {
  if (typeof document === "undefined") return;
  const language = getLanguage();
  document.documentElement.lang = language;
  document.documentElement.dir = getDirection(language);
  document.documentElement.dataset.language = language;
}

export function setLanguage(language) {
  if (typeof window === "undefined" || !SUPPORTED_LANGUAGES.has(language)) return;
  window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
  window.location.reload();
}

export function toggleLanguage() {
  setLanguage(getLanguage() === "fa" ? "en" : "fa");
}

export function translate(value) {
  if (getLanguage() !== "en" || typeof value !== "string") return value;

  const leadingWhitespace = value.match(/^\s*/u)?.[0] ?? "";
  const trailingWhitespace = value.match(/\s*$/u)?.[0] ?? "";
  const core = value.slice(leadingWhitespace.length, value.length - trailingWhitespace.length);
  const translated = ENGLISH_TRANSLATIONS[core] ?? core;
  const latinDigits = translated.replace(/[۰-۹]/gu, (digit) => String(PERSIAN_DIGITS.indexOf(digit)));
  return `${leadingWhitespace}${latinDigits}${trailingWhitespace}`;
}

export function formatNumber(value, options) {
  return new Intl.NumberFormat(getLocale(), options).format(value);
}

export function formatDate(value, options) {
  return new Intl.DateTimeFormat(getLocale(), options).format(value);
}

export function isTranslated(value) {
  return Object.prototype.hasOwnProperty.call(ENGLISH_TRANSLATIONS, value);
}
